  await page.getByRole('button',{name:'Markdownをコピー',exact:true}).click();
  await page.screenshot({path:'WORK/screenshots/report-desktop.png',fullPage:true});
  await page.reload();
  await page.getByRole('heading',{name:'月次レポート',exact:true}).waitFor();
  await nav.getByRole('link',{name:'ホーム',exact:true}).click();
  await page.getByRole('heading',{name:'A社',exact:true}).waitFor();
