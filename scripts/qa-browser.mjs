  assert.equal(await page.getByLabel('企画メモ',{exact:true}).inputValue(),'遅延応答中の新しい下書きです');
  await page.unroute('**/api/projects/*/channel');
  const nav=page.getByRole('navigation',{name:'制作の流れ'});
  await nav.getByRole('link',{name:'企画メモ・企画シート',exact:true}).click();
  await page.getByLabel('企画メモ',{exact:true}).fill('転職でよくある質問に答える企画です');
  await page.getByRole('button',{name:'自動分類する',exact:true}).click();
  await page.getByRole('button',{name:'企画シートを作成',exact:true}).waitFor();
  await page.getByLabel('企画型',{exact:true}).selectOption('faq');
  await page.getByRole('button',{name:'企画シートを作成',exact:true}).click();
  await page.getByRole('heading',{name:'タイトル案',exact:true}).waitFor();
  await nav.getByRole('link',{name:'台本構成・撮影チェックリスト',exact:true}).click();
  await page.getByRole('button',{name:'台本構成を作成',exact:true}).click();
  await page.getByLabel('話すことの要点',{exact:true}).first().fill('最初に転職の悩みを紹介します');
  await page.getByLabel('撮影メモ',{exact:true}).first().fill('正面から撮影します');
  await page.getByRole('button',{name:'要点・撮影メモを保存',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[role="status"]')?.textContent==='保存しました。');
  await nav.getByRole('link',{name:'スケジュール',exact:true}).click();
  await page.getByLabel('投稿日',{exact:true}).fill('2099-10-30');
  await page.getByRole('button',{name:'逆算スケジュールを作成',exact:true}).click();
  await page.getByLabel('企画確定 状態',{exact:true}).selectOption('done');
  await page.getByRole('button',{name:'更新',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('[role="status"]')?.textContent==='保存しました。');
  await nav.getByRole('link',{name:'編集指示書',exact:true}).click();
  await page.getByRole('button',{name:'編集指示書を作成',exact:true}).click();
  await page.getByText(/話すことの要点: 最初に転職の悩みを紹介します/).waitFor();
  await mkdir('WORK/screenshots',{recursive:true});
  await page.screenshot({path:'WORK/screenshots/brief-desktop.png',fullPage:true});
  await nav.getByRole('link',{name:'月次レポート',exact:true}).click();
  await page.locator('input[name="month"]').fill('2026-09');
  await page.locator('input[name="month"]').blur();
