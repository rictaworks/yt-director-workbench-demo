  const delayed = new Promise(resolve => { releaseSave = resolve; });
  await page.route('**/api/projects/*/channel', async route => {
    const reply = await route.fetch(); await delayed; await route.fulfill({response:reply});
  });
  await page.getByRole('button',{name:'設計を保存',exact:true}).click();
  await page.getByRole('navigation',{name:'制作の流れ'}).getByRole('link',{name:'企画メモ・企画シート',exact:true}).click();
